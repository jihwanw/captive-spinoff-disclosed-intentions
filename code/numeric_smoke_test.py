#!/usr/bin/env python3
"""numeric_smoke_test.py — single-source-of-truth check for the CGIR manuscript (run before every build that is sent anywhere).

Checks
  A  Determinism / staleness: re-running code/make_tables_cgir.py into a temporary copy reproduces paper/tables/*.tex and numbers.tex
     byte for byte (apart from the generation-date comment). A difference means the tables in the PDF are stale or the generator
     is non-deterministic.
  B  Macro coverage: every \\Macro used in paper/tex/sec*.tex and supplement.tex is defined in numbers.tex; every macro defined is used
     somewhere (tex or tables) — unused macros are reported as WARN (they are harmless but suggest a dropped sentence).
  C  Rendered values: the PDF text contains the rendered value of each headline macro (AUC, Spearman, slopes, reform shares, n's).
  D  No typed statistics: digit tokens in the prose (outside macros, citations, refs, math windows, dates, method constants) must be
     empty. Method constants and dates are whitelisted explicitly below; anything else is a FAIL and must become a macro.
Prints RESULT: PASS / RESULT: FAIL (exit 1) — the submission gate greps for the PASS line.
"""
import os, re, sys, glob, shutil, subprocess, tempfile
from pathlib import Path
P = Path(__file__).resolve().parent.parent
TEX = P / "paper/tex"; TAB = P / "paper/tables"
fails, warns = [], []

# ---- A: regenerate into a scratch copy of the project (tables dir only is written by the generator)
with tempfile.TemporaryDirectory() as td:
    scratch = Path(td) / "proj"; scratch.mkdir()
    for d in ("code", "results", "literature"):
        shutil.copytree(P / d, scratch / d, ignore=shutil.ignore_patterns("__pycache__"))
    (scratch / "data").symlink_to(P / "data")
    (scratch / "paper").mkdir(); (scratch / "paper/tables").mkdir()
    r = subprocess.run([sys.executable, str(scratch / "code/make_tables_cgir.py")], capture_output=True, text=True, cwd=scratch)
    if r.returncode != 0:
        fails.append("A generator failed in scratch run: " + r.stderr.strip().splitlines()[-1][:200])
    else:
        def strip_date(s): return re.sub(r"generated by code/make_tables_cgir\.py on \d{4}-\d{2}-\d{2}", "generated", s)
        for f in sorted((scratch / "paper/tables").glob("*.tex")):
            cur = TAB / f.name
            if not cur.exists(): fails.append(f"A {f.name} missing from paper/tables"); continue
            if strip_date(f.read_text()) != strip_date(cur.read_text()): fails.append(f"A {f.name} differs from the regenerated version (stale table or non-deterministic generator)")
        for cur in TAB.glob("*.tex"):
            if not (scratch / "paper/tables" / cur.name).exists(): warns.append(f"A {cur.name} exists in paper/tables but is not produced by the generator")

# ---- B: macro coverage
nums = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}", (TAB / "numbers.tex").read_text()))
archive_macros = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}", (TEX / "archive_ids.tex").read_text())) if (TEX / "archive_ids.tex").exists() else {}
tex_files = sorted(TEX.glob("sec*.tex")) + [TEX / "supplement.tex"]
used = set()
body_all = ""
for f in tex_files:
    t = re.sub(r"(?<!\\)%.*", "", f.read_text()); body_all += "\n" + t
    used |= set(re.findall(r"\\([A-Z][A-Za-z]+)(?:\{\})?", t))
latex_cmds = {"NDefs"}  # harmless
undefined = sorted(u for u in used if u not in nums and u not in archive_macros and re.match(r"^[A-Z]", u) and u not in ("KOSPI", "KOSDAQ", "OLS", "AUC", "ROC", "HC", "BHAR", "CAR", "DART", "US", "LG", "CJ", "ENM", "DB", "SK", "GPT", "BM", "FF", "NW", "MW", "SI", "FE"))
# only names that look like our macros (CamelCase starting with capital and containing lowercase)
undefined = [u for u in undefined if re.search(r"[a-z]", u) and u not in ("Note", "Model", "Section", "Table", "Tables", "Supporting")]
if undefined: fails.append(f"B macros used but undefined: {undefined}")
tables_txt = "".join(f.read_text() for f in TAB.glob("T_*.tex")) + "".join(f.read_text() for f in TAB.glob("S_*.tex"))
unused = sorted(k for k in nums if k not in used)
if unused: warns.append(f"B macros defined but never used in prose: {unused}")

# ---- C: rendered values in the PDF
pdf = TEX / "main.pdf"
txt = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], capture_output=True, text=True).stdout
txt_n = txt.replace("\u2212", "-").replace("\u2013", "-")
HEAD = ["AUCPooledLLM", "AUCPooledFin", "SpearmanScoreBhar", "AnnCarSlope", "EarlyNeverDiff", "ScoreOnBlock", "ProtectPre", "ProtectPost", "CarPost", "NGateOne", "NScoreOneY", "LowBlockMedian", "HighBlockMedian", "AUCOldIdent", "AUCOldAnon", "RankSpecThreeCoef"]
for k in HEAD:
    v = nums[k].replace("$-$", "-").replace("$<$", "<")
    if v not in txt_n: fails.append(f"C headline macro {k}={v} not found in the rendered PDF text")

# ---- D: typed statistics in prose
WHITELIST_PATTERNS = [   # applied in order: multi-character constants first, single digits last
    r"\b(19|20)\d{2}--(19|20)\d{2}\b", r"\b(19|20)\d{2}\b",            # year ranges and years
    r"\b\d{1,2} (January|February|March|April|May|June|July|August|September|October|November|December)\b",   # dates
    r"\b99\.5\b", r"\b60,000\b", r"\b10,000\b", r"\b100\b", r"\b250\b", r"\b130\b", r"\b90\b", r"\b50\b", r"\b31\b",   # method constants stated in Section 3 / table notes
    r"\b0\.5\b", r"\b0\.01\b", r"\b0\.05\b", r"\b0\.10\b",             # chance level, significance levels
    r"\b0--1\b", r"\b1--3\b", r"\b5-1\b", r"\b6\.1\b", r"\b10-K\b", r"\b3pt\b", r"Article 165-5\(3\)",   # scales, antecedent table range, model versions, statute citation
    r"\b(14|18|17|23|27|28|30)\b",                                         # footnote numbers of the antecedent and day numbers that survive the date pattern
    r"\b[0-6]\b",                                                          # column numbers, Day 0, scale endpoints
]
def prose_only(t):
    t = re.sub(r"\\(?:cite[A-Za-z]*|ref|label|input|texttt)\{[^}]*\}", " ", t)
    t = re.sub(r"\\[A-Za-z]+(?:\{\})?", " ", t)             # macros and commands
    t = re.sub(r"\$[^$]*\$", " ", t)                        # math windows (-1, +1, +250 ...)
    t = re.sub(r"\\begin\{[^}]*\}|\\end\{[^}]*\}|\[htbp\]", " ", t)
    return t
typed = []
for f in sorted(TEX.glob("sec*.tex")):
    t = prose_only(re.sub(r"(?<!\\)%.*", "", f.read_text()))
    for pat in WHITELIST_PATTERNS: t = re.sub(pat, " ", t)
    for m in re.finditer(r"(?<![A-Za-z])\d[\d,.]*", t):
        ctx = t[max(0, m.start()-40):m.end()+25].replace("\n", " ")
        typed.append(f"{f.name}: '{m.group(0)}' …{ctx}…")
if typed: fails.append("D typed numbers in prose (make them macros or whitelist as method constants):\n   " + "\n   ".join(typed[:30]))

for w in warns: print("WARN", w)
for x in fails: print("FAIL", x)
print(f"checks: A determinism, B macro coverage ({len(nums)} macros, {len(used & set(nums))} used), C {len(HEAD)} headline values, D typed numbers")
print("RESULT:", "FAIL" if fails else "PASS")
sys.exit(1 if fails else 0)
